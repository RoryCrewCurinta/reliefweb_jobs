filter_js = """<script>
(function(){
  var q=document.getElementById("tq"); if(!q) return;
  var cards=[].slice.call(document.querySelectorAll("#tlist .topic")), groups=[].slice.call(document.querySelectorAll("#tlist .tgroup"));
  var cnt=document.getElementById("tcount"), none=document.getElementById("tnone"), total=cards.length;
  q.addEventListener("input",function(){
    var w=q.value.trim().toLowerCase().split(/\\s+/).filter(Boolean), n=0;
    cards.forEach(function(c){var h=c.getAttribute("data-q"), ok=w.every(function(x){return h.indexOf(x)>-1;}); c.hidden=!ok; if(ok) n++;});
    groups.forEach(function(g){g.hidden=!g.querySelector(".topic:not([hidden])");});
    cnt.textContent=w.length? n+" of "+total+" topics" : total+" topics"; none.hidden=n>0;
  });
})();
</script>"""
