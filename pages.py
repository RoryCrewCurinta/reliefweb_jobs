def topic_card(t):
    name = t["dashboard_name"] or t["topic"]
    d = DEF_OVERRIDE.get(t["topic"], t["definition"])
    wl = '<span class="wl">Exploratory</span>' if t["topic"] in THIN_TOPICS else ""
    dl = ""
    if t["includes"].strip(): dl += f"<dt>Includes</dt><dd>{E(t['includes'])}</dd>"
    if t["excludes"].strip(): dl += f"<dt>Not here</dt><dd>{E(t['excludes'])}</dd>"
    hay = E(" ".join([name, t["topic"], d, t["includes"], t["excludes"], t["group"]]).lower())
    return (f'<div class="topic" data-q="{hay}"><h4>{E(name)}{wl}</h4><p>{E(d)}</p>'
            + (f"<dl>{dl}</dl>" if dl else "") + "</div>")
groups = []
for t in topics:
    if t["group"] not in groups: groups.append(t["group"])
topic_html = "".join(
    f'<div class="tgroup"><h3>{E(g)}</h3>' + "".join(topic_card(t) for t in topics if t["group"] == g) + "</div>"
    for g in groups)
