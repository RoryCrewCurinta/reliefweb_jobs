def toc(items):
    return '<nav class="toc" aria-label="On this page"><b>On this page</b><ol>' + "".join(
        f'<li><a href="#{i}">{E(t)}</a></li>' for i, t in items) + "</ol></nav>"

def h2(t):
    return f'<h2><span class="pix" aria-hidden="true"></span>{t}</h2>'

