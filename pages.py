"""Build the Methodology and Glossary pages (docs/methodology.html, docs/glossary.html).

Run after export.py:  python pages.py
- Figures (totals, date range, quiet months) come from docs/data/meta.json and totals_by_year.csv.
- Topic names, groups and definitions come from review/topics_v2_definitions.csv, so the glossary
  stays in step with what the model was told. DEF_OVERRIDE changes display wording only.
- The Curinta banner, favicon and menu script are copied from docs/index.html, so edit them there.
- Styles live in docs/site.css.
"""
import csv, html, json, re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = ROOT / "docs"
DATA = DOCS / "data"
SITE = "https://trendlines.curinta.com"
E = html.escape

# Keep in step with export.py
THIN_TOPICS = {"Stablecoins & digital assets", "Group cash transfers", "Blockchain & crypto", "Biometrics",
               "Humanitarian reset & reform", "Digital payments & financial service providers",
               "Cash coordination", "Interoperability & data sharing"}
# Display-only wording fixes (the CSV is the model's prompt, so it is left as tagged)
DEF_OVERRIDE = {
    "Impact evaluation & research": "Research and study roles and evaluation consultancies in general, "
                                    "not only rigorous impact evaluations.",
}
MONTHS = "January February March April May June July August September October November December".split()

def month_name(ym):
    y, m = ym.split("-"); return f"{MONTHS[int(m)-1]} {y}"

def short_month(ym):
    y, m = ym.split("-"); return f"{MONTHS[int(m)-1][:3]} {y}"

meta = json.loads((DATA / "meta.json").read_text(encoding="utf-8"))
years = {int(r["year"]): int(r["n_posts"]) for r in csv.DictReader(open(DATA / "totals_by_year.csv", encoding="utf-8"))}
topics = list(csv.DictReader(open(ROOT / "review" / "topics_v2_definitions.csv", encoding="utf-8-sig")))
index = (DOCS / "index.html").read_text(encoding="utf-8")

banner = re.search(r'<header class="site" id="site">.*?</header>', index, re.S).group(0)
banner = banner.replace('href="curinta-logo.png"', 'href="curinta-logo.png"').replace('src="curinta-logo.png"', 'src="curinta-logo.png"')
favicon = re.search(r'<link rel="icon"[^>]*>', index).group(0)
menu_js = re.search(r'<script>\s*\(function\(\)\{\s*var site=document.getElementById\("site"\).*?</script>', index, re.S).group(0)
og_image = re.search(r'<meta property="og:image" content="([^"]+)"', index).group(1)
logo_src = re.search(r'<footer class="colophon">\s*<span><img src="([^"]+)"', index).group(1)

total = meta["total_jobs"]; first = meta["first_month"]; last = meta["last_month"]
full_years = sorted(y for y in years if y < int(last[:4]))
peak_year = max(full_years, key=lambda y: years[y]); latest_full = full_years[-1]
n_topics = len(topics)
n_groups = len({t["group"] for t in topics})

